function minInsertions(s: string): number {
    let res = 0;      // تعداد درج‌های لازم
    let needed = 0;   // تعداد پرانتزهای بسته مورد نیاز

    for (let i = 0; i < s.length; i++) {
        const char = s[i];

        if (char === '(') {
            // اگر یک پرانتز بسته تک‌افتاده نیاز داریم، آن را همین‌جا اضافه می‌کنیم
            if (needed % 2 !== 0) {
                res++;      // درج یک ')'
                needed--;   // رفع نیاز آن
            }
            needed += 2; // هر '(' به دو ')' نیاز دارد
        } else { // char === ')'
            needed--;

            // اگر پرانتز باز کم داریم
            if (needed < 0) {
                res++;       // درج یک '('
                needed = 1;  // یک '(' اضافه شد (+2 نیازمندی)، اما یک ')' هم داشتیم -> 2 - 1 = 1
            }
        }
    }

    // اضافه کردن پرانتزهای بسته باقی‌مانده در انتها
    return res + needed;
};